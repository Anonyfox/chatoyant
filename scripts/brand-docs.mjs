for (const asset of ASSETS) await cp(join(ROOT, "assets", asset), join(OUT, asset));

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) {
      await chmod(p, 0o755); // dune output is read-only; make the copy writable
      yield* walk(p);
    } else {
      yield p;
    }
  }
}

const escapeAttr = (s) =>
  s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const decode = (s) =>
  s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");

const plain = (html) => decode(html.replace(/<[^>]+>/g, "")).replace(/\s+/g, " ").trim();

// Absolute URL for a page; index.html pages use their directory URL.
function pageUrl(file) {
  const rel = relative(OUT, file).split(sep).join("/");
  return SITE + rel.replace(/(^|\/)index\.html$/, "$1");
}

// First paragraph of odoc's preamble (the module's doc comment), else a
// sentence naming the module.
function describe(html, title) {
  const preamble = html.match(/<header class="odoc-preamble">([\s\S]*?)<\/header>/);
  const para = preamble?.[1].match(/<p>([\s\S]*?)<\/p>/);
  let text = para ? plain(para[1]) : "";
  const name = title.replace(/\s*\(.*$/, "");
  if (text.length < 40) {
    text = `${text ? `${text} ` : ""}API reference for ${name} in Chatoyant, an OCaml-first SDK for LLM providers.`;
  }
  if (text.length > 160) text = `${text.slice(0, 157).replace(/\s+\S*$/, "")}…`;
  return text;
}

// Measured-number panels injected at the end of an intent page's preamble, so
// they sit under the opening answer on every screen size. Every number is read
// from a committed source at build time: the SDK size snapshot in doc/data and
// the price and context-window tables in lib/tokens. Nothing is retyped here.
const fmtMB = (b) => `${(b / 1024 / 1024).toFixed(1)} MB`;
const fmtKB = (b) => `${(b / 1024).toFixed(1)} KB`;
const fmtDate = (iso) =>
  new Date(`${iso}T00:00:00Z`).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });

function bars(title, rows, key, fmt) {
  const max = Math.max(...rows.map((r) => r[key]));
  return `<div class="chatoyant-bars" role="group" aria-label="${escapeAttr(title)}"><h3>${title}</h3>` +
    rows.map((r) =>
      `<div class="chatoyant-bar${r.name === "chatoyant" || r.highlight ? " is-us" : ""}">` +
      `<span class="chatoyant-bar-label">${escapeAttr(r.name)}${r.detail ? ` <small>${escapeAttr(r.detail)}</small>` : ""}</span>` +
      `<span class="chatoyant-bar-track" aria-hidden="true"><span class="chatoyant-bar-fill" style="width:${((r[key] / max) * 100).toFixed(2)}%"></span></span>` +
      `<span class="chatoyant-bar-value">${fmt(r[key])}</span></div>`).join("") +
    "</div>";
}

async function sizeFigure() {
  const dir = join(ROOT, "doc/data");
  const latest = (await readdir(dir)).filter((f) => /^sdk-size-\d{4}-\d{2}-\d{2}\.json$/.test(f)).sort().at(-1);
  if (!latest) throw new Error("brand-docs: no doc/data/sdk-size-*.json snapshot");
  const data = JSON.parse(await readFile(join(dir, latest), "utf8"));
  const rows = data.rows;
  const us = rows.find((r) => r.name === "chatoyant");
  const others = rows.filter((r) => r !== us);
  const range = (key, fmt) => {
    const v = others.map((r) => r[key]);
    return `${fmt(Math.min(...v))} to ${fmt(Math.max(...v))}`;
  };
  return '<section class="chatoyant-figure" aria-labelledby="size-at-a-glance">' +
    `<h2 class="chatoyant-figure-title" id="size-at-a-glance">One text call, five SDKs, measured ${fmtDate(data.date)}</h2>` +
    `<p class="chatoyant-figure-lede">chatoyant installs <strong>${fmtMB(us.installBytes)}</strong> and bundles to ` +
    `<strong>${fmtKB(us.gzipBytes)}</strong> gzip. The other four install ${range("installBytes", fmtMB)} ` +
    `and bundle to ${range("gzipBytes", fmtKB)}.</p>` +
    bars("Install size (node_modules)", rows, "installBytes", fmtMB) +
    bars("Bundle, minified and gzipped", rows, "gzipBytes", fmtKB) +
    `<p class="chatoyant-figure-note">Fresh <code>npm install</code> on Node ${escapeAttr(data.node)}, esbuild bundle of one call. ` +
    `Source: <a href="https://github.com/Anonyfox/chatoyant/blob/main/doc/data/${latest}">doc/data/${latest}</a>.</p>` +
    "</section>";
}

async function costFigure() {
  const pricing = await readFile(join(ROOT, "lib/tokens/pricing.ml"), "utf8");
  const windows = await readFile(join(ROOT, "lib/tokens/context_window.ml"), "utf8");
  const models = [
    ["OpenAI", "gpt-6.1-sol"],
    ["Anthropic", "claude-sonnet-5-5"],
    ["xAI", "grok-4.7"],
  ];
  const IN = 1000, OUT = 200;
  const cards = models.map(([provider, id]) => {
    const esc = id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const row = pricing.match(new RegExp(`\\(\\s*"${esc}",\\s*p\\s+([^)]*)\\(\\)\\s*\\)`))?.[1];
    const ctx = windows.match(new RegExp(`\\("${esc}",\\s*([\\d_]+)\\)`))?.[1];
    if (!row || !ctx) throw new Error(`brand-docs: ${id} missing from pricing.ml or context_window.ml`);
    const rate = (k) => Number(row.match(new RegExp(`~${k}:([\\d.]+)`))?.[1]);
    const input = rate("input"), output = rate("output"), cached = rate("cached");
    const cost = (IN * input + OUT * output) / 1e6;
    const tokens = Number(ctx.replace(/_/g, ""));
    return { provider, id, input, output, cached, cost, tokens };
  });
  const usd = (n) => `$${n.toFixed(2)}`;
  const rows = cards.map((c) => ({
    name: `${c.provider} ${c.id}`,
    detail: `${usd(c.input)} in, ${usd(c.output)} out, ${usd(c.cached)} cached per 1M; ${c.tokens.toLocaleString("en-US")}-token context`,
    cost: c.cost,
    highlight: true,
  }));
  return '<section class="chatoyant-figure" aria-labelledby="cost-at-a-glance">' +
    '<h2 class="chatoyant-figure-title" id="cost-at-a-glance">The three models in this guide, side by side</h2>' +
    `<p class="chatoyant-figure-lede">Estimated cost of one request with ${IN.toLocaleString("en-US")} uncached input and ${OUT} output tokens, ` +
    "from the rates chatoyant uses for its own cost accounting.</p>" +
    bars(`Cost of ${IN.toLocaleString("en-US")} input + ${OUT} output tokens`, rows, "cost", (n) => `$${n.toFixed(4)}`) +
    '<p class="chatoyant-figure-note">USD per million tokens. Source: ' +
    '<a href="https://github.com/Anonyfox/chatoyant/blob/main/lib/tokens/pricing.ml">lib/tokens/pricing.ml</a> and ' +
    '<a href="https://github.com/Anonyfox/chatoyant/blob/main/lib/tokens/context_window.ml">context_window.ml</a>. ' +
    "Caching discounts and long-context tiers are not included.</p>" +
    "</section>";
}

const FIGURES = new Map([
  [join(OUT, "chatoyant/js_llm_sdk_size.html"), await sizeFigure()],
  [join(OUT, "chatoyant/ocaml_llm_guide.html"), await costFigure()],
]);

const urls = [];
for await (const file of walk(OUT)) {
  await chmod(file, 0o644);
  if (!file.endsWith(".html")) continue;

  let html = await readFile(file, "utf8");
  const url = pageUrl(file);
  urls.push(url);

  if (file === INDEX) {
    html = html
      .replace("<title>index</title>", "<title>Chatoyant: OCaml-first LLM SDK</title>")
      .replace("<h2>OCaml package documentation</h2>", HERO);
  } else if (GUIDES.has(file)) {
    html = html.replace(/<title>[^<]*<\/title>/, `<title>${GUIDES.get(file).title}</title>`);
    if (FIGURES.has(file)) {
      const at = html.indexOf("</header>");
      if (at < 0) throw new Error(`brand-docs: no preamble in ${file}`);
      html = html.slice(0, at) + FIGURES.get(file) + html.slice(at);
    }
  } else if (file === PACKAGE_INDEX) {
    html = html.replace(
      /<title>[^<]*<\/title>/,
      `<title>Chatoyant ${version} API reference: libraries and entry modules</title>`,
    );
  }

  if (file === PACKAGE_INDEX) {
    const links = [...GUIDES].map(([path, guide]) =>
      `<p><a href="${relative(dirname(file), path).split(sep).join("/")}">${guide.label}</a>: ${guide.summary}.</p>`).join("");
    html = html.replace('<div class="odoc-content">', `<div class="odoc-content">${links}`);
  }

  const title = plain(html.match(/<title>([\s\S]*?)<\/title>/)?.[1] ?? "Chatoyant");
  const description = file === INDEX ? SUMMARY : GUIDES.has(file) ? GUIDES.get(file).description : describe(html, title);
  const fav = relative(dirname(file), join(OUT, FAVICON)).split(sep).join("/");
  const head = [
    `<link rel="canonical" href="${url}"/>`,
    `<meta name="description" content="${escapeAttr(description)}"/>`,
    `<meta property="og:type" content="website"/>`,
    `<meta property="og:site_name" content="Chatoyant"/>`,
    `<meta property="og:title" content="${escapeAttr(title)}"/>`,
    `<meta property="og:description" content="${escapeAttr(description)}"/>`,
    `<meta property="og:url" content="${url}"/>`,
    `<meta property="og:image" content="${OG_IMAGE}"/>`,
    `<meta property="og:image:width" content="512"/>`,
    `<meta property="og:image:height" content="512"/>`,
    `<meta property="og:image:alt" content="Chatoyant logo"/>`,
    `<meta name="twitter:card" content="summary"/>`,
    `<link rel="icon" type="image/png" sizes="64x64" href="${fav}"/>`,
  ];
  if (file === INDEX) {
    const ld = {
      "@context": "https://schema.org",
      "@type": "SoftwareSourceCode",
      name: "Chatoyant",
      description: SUMMARY,
      url: SITE,
      codeRepository: REPO,
      programmingLanguage: ["OCaml", "JavaScript"],
      license: "https://opensource.org/licenses/MIT",
      version,
      author: { "@type": "Person", name: "Anonyfox", url: "https://anonyfox.com" },
    };
    head.push(`<script type="application/ld+json">${JSON.stringify(ld)}</script>`);
    head.push(`<meta name="msvalidate.01" content="87D8EC84DD2BC0419BCA605CBBD5E36F"/>`);
  }

  const ids = new Map();
  html = html
    .replace(/<html(?![^>]*\blang=)/, '<html lang="en"')
    // odoc has no <main>; mark its content column as the main landmark.
    .replace('<div class="odoc-content">', '<div class="odoc-content" role="main">')
    // odoc gives inline-record fields of different constructors the same id
    // (type-t.field); suffix repeats so ids stay unique, with their permalink.
    .replace(/\sid="([^"]+)"([^>]*>)(<a href="#\1" class="anchor">)?/g, (m, id, rest, anchor) => {
      const n = (ids.get(id) ?? 0) + 1;
      ids.set(id, n);
      if (n === 1) return m;
      const unique = `${id}-${n}`;
      return ` id="${unique}"${rest}${anchor ? `<a href="#${unique}" class="anchor">` : ""}`;
    })
    // odoc's hover permalinks are empty <a> elements; give them a name.
    .replace(
      /<a href="#([^"]+)" class="anchor"><\/a>/g,
      (_, id) => `<a href="#${id}" class="anchor" aria-label="Permalink to ${escapeAttr(decode(id))}"></a>`,
    )
    // Wide tables scroll inside their own box instead of widening the page.
    // Package names in cells may break after a "/" or before a version "@".
    .replace(/<table class="odoc-table">[\s\S]*?<\/table>/g, (t) =>
      `<div class="chatoyant-table-scroll">${t.replace(/<code>([^<]*)<\/code>/g, (_, c) =>
        `<code>${c.replace(/\//g, "/<wbr>").replace(/(?<=\w)@/g, "<wbr>@")}</code>`)}</div>`)
    .replace(/<meta name="description"[^>]*>\s*/g, "")
    .replace("</head>", `${head.join("")}</head>`);
  if (html.includes("</body>") && !html.includes("chatoyant-footer")) {
    html = html.replace("</body>", `${FOOTER}</body>`);
  }

  await writeFile(file, html);
}

// odoc.css: let text render in the fallback font while webfonts load, then
// append the brand overlay.
const brand = await readFile(CSS_SRC, "utf8");
const css = (await readFile(ODOC_CSS, "utf8")).replace(
  /@font-face\s*\{(?![^}]*font-display)/g,
  "@font-face {\n  font-display: swap;",
);
await writeFile(ODOC_CSS, `${css}\n/* chatoyant-brand */\n${brand}`);

// Resolve odoc module paths (including nested modules) to their source file.
const tracked = (await exec("git", ["ls-files", "lib", "doc", "*.md"], { cwd: ROOT, encoding: "utf8" })).stdout.trim().split("\n");
const dateCache = new Map();
async function lastCommit(files) {
  const key = files.join("\0");
  if (!dateCache.has(key)) dateCache.set(key,
    (await exec("git", ["log", "-1", "--format=%cs", "--", ...files], { cwd: ROOT, encoding: "utf8" })).stdout.trim());
  return dateCache.get(key);
}
const fallbackDate = await lastCommit(["lib/", "doc/"]);
async function lastmod(url) {
  const parts = decodeURIComponent(url.slice(SITE.length)).split("/").filter(p => p && p !== "index.html");
  for (const part of parts.slice(1).reverse()) {
    const name = part.replace(/\.html$/, "").toLowerCase();
    for (const ext of ["mli", "ml"]) {
      const source = tracked.find(f => f.startsWith("lib/") && f.split("/").at(-1).toLowerCase() === `${name}.${ext}`);
      if (source) return (await lastCommit([source])) || fallbackDate;
    }
  }
  const name = (parts.at(-1) || "readme").replace(/^(page-)|\.html$/g, "").toLowerCase();
  const source = tracked.find(f => /\.(mld|md)$/i.test(f) && f.split("/").at(-1).replace(/\.(mld|md)$/i, "").toLowerCase() === name);
  return source ? (await lastCommit([source])) || fallbackDate : fallbackDate;
}

// Crawler and LLM entry points.
urls.sort((a, b) => a.length - b.length || a.localeCompare(b));
await writeFile(
  join(OUT, "sitemap.xml"),
  '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    (await Promise.all(urls.map(async (u) => `  <url><loc>${escapeAttr(u)}</loc><lastmod>${await lastmod(u)}</lastmod></url>\n`))).join("") +
    "</urlset>\n",
);
await writeFile(join(OUT, "robots.txt"), `User-agent: *\nAllow: /\n\nSitemap: ${SITE}sitemap.xml\n`);

const entryModules = (await readdir(join(OUT, "chatoyant"), { withFileTypes: true }))
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();
const blob = (f) => `${REPO}/blob/main/${f}`;
await writeFile(
  join(OUT, "llms.txt"),
  [
    "# Chatoyant",
    "",
    `> ${SUMMARY}`,
    "",
    `Version ${version}, MIT license. Published as the npm package \`chatoyant\` and the opam package \`chatoyant\`. ` +
      `The npm package has a single root import path, ESM and CommonJS entrypoints and bundled .d.ts/.d.cts declarations. ` +
      `This site is the odoc API reference for the OCaml libraries (${urls.length} pages).`,
    "",
    "## Docs",
    "",
    `- [README](${blob("README.md")}): overview, install, providers, package size table`,
    `- [JAVASCRIPT.md](${blob("JAVASCRIPT.md")}): JavaScript and TypeScript guide for the npm package`,
    `- [OCAML.md](${blob("OCAML.md")}): OCaml guide (Eio runtime, ppx codecs, typed tools)`,
    `- [OCaml LLM guide](${SITE}chatoyant/ocaml_llm_guide.html): GPT-6, Claude 5.5 and Grok 4.7 with Eio`,
    `- [JavaScript LLM SDK sizes](${SITE}chatoyant/js_llm_sdk_size.html): measured install and bundle bytes, method and TypeScript example`,
    `- [API reference](${SITE}chatoyant/): odoc reference for every OCaml library in the package`,
    "",
    "## API entry modules",
    "",
    ...entryModules.map((m) => `- [${m}](${SITE}chatoyant/${m}/)`),
    "",
    "## Packages",
    "",
    "- [npm](https://www.npmjs.com/package/chatoyant): `npm install chatoyant`",
    "- [opam](https://opam.ocaml.org/packages/chatoyant/): `opam install chatoyant`",
    "",
    "## Optional",
    "",
    `- [CHANGELOG](${blob("CHANGELOG.md")}): release history`,
    `- [Source](${REPO}): GitHub repository`,
    "",
  ].join("\n"),
);

// Search engine ownership files (Google, Bing, IndexNow key), copied byte-for-byte after
// branding and the sitemap so they are neither rewritten nor listed.
const VERIFY = join(ROOT, "doc", "site-verification");
if (existsSync(VERIFY)) {
  for (const name of await readdir(VERIFY)) await cp(join(VERIFY, name), join(OUT, name));
}
await writeFile(join(OUT, ".nojekyll"), "");

console.log(`brand-docs: built ${OUT} (${urls.length} pages, sitemap.xml, robots.txt, llms.txt)`);
